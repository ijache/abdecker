#!/usr/bin/env python3
"""Generates the data the rule checker needs.

1. data/codelists.txt  - code lists, extracted from the official EN 16931
   validation artefacts (CEN, EUPL 1.2; only the code values are taken).
   Only regenerated when testdata/rules exists (tools/fetch-testdata.sh).
2. source/abdecker.rules.inc - Pascal constants built from data/rules.txt and
   data/codelists.txt. Also checks that every rule ID used in
   source/abdecker.check.pas is defined in data/rules.txt.

3. cli/openapi.inc - the OpenAPI description of "abdecker serve"
   (data/openapi.json) as a Pascal string constant, served at /openapi.json.

The data files are language neutral, so a port (e.g. Go) can use them too.
Run:  python tools/gen-data.py
"""
import html
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RULES_DIR = os.path.join(ROOT, 'testdata', 'rules')
CODELISTS = os.path.join(ROOT, 'data', 'codelists.txt')
RULES = os.path.join(ROOT, 'data', 'rules.txt')
INC = os.path.join(ROOT, 'source', 'abdecker.rules.inc')
CHECK = os.path.join(ROOT, 'source', 'abdecker.check.pas')
OPENAPI = os.path.join(ROOT, 'data', 'openapi.json')
OPENAPI_INC = os.path.join(ROOT, 'cli', 'openapi.inc')


def read(p):
    with open(p, encoding='utf-8') as f:
        return f.read()


def asserts(path):
    """rule id -> test expression (params resolved where possible)"""
    s = read(path)
    params = {n: html.unescape(v) for n, v in re.findall(r'<param\s+name="([^"]+)"\s+value="([^"]*)"', s)}
    out = {}
    for a in re.finditer(r'<assert([^>]*)>', s):
        at = a.group(1)
        i = re.search(r'id="([^"]+)"', at)
        t = re.search(r'test="([^"]*)"', at)
        if i and t:
            test = html.unescape(t.group(1))
            if test.startswith('$') and test[1:] in params:
                test = params[test[1:]]
            out[i.group(1)] = test
    for n, v in params.items():
        out.setdefault(n, v)
    return out


def lists_in(test):
    found = [c.split() for c in re.findall(r"contains\(\s*'\s*([^']+?)\s*'", test)]
    mimes = re.findall(r"@mimeCode\s*=\s*'([^']+)'", test)
    if mimes:
        found.append(mimes)
    return found


def extract_codelists():
    ubl = {}
    ubl.update(asserts(os.path.join(RULES_DIR, 'en16931-ubl/schematron/codelist/EN16931-UBL-codes.sch')))
    ubl.update(asserts(os.path.join(RULES_DIR, 'en16931-ubl/schematron/UBL/EN16931-UBL-model.sch')))
    cii = {}
    cii.update(asserts(os.path.join(RULES_DIR, 'en16931-cii/schematron/codelist/EN16931-CII-codes.sch')))
    cii.update(asserts(os.path.join(RULES_DIR, 'en16931-cii/schematron/CII/EN16931-CII-model.sch')))

    def one(src, rid, idx=0):
        ls = lists_in(src.get(rid, ''))
        if not ls:
            sys.exit('no code list in ' + rid)
        return ls[idx]

    def same(name, a, b):
        if sorted(set(a)) != sorted(set(b)):
            print('note: %s differs between UBL and CII: +UBL %s +CII %s' % (
                name, sorted(set(a) - set(b))[:10], sorted(set(b) - set(a))[:10]))
        return sorted(set(a) | set(b))

    lists = {
        'UNTDID1001-INVOICE': one(ubl, 'BR-CL-01', 0),
        'UNTDID1001-CREDITNOTE': one(ubl, 'BR-CL-01', 1),
        'UNTDID1001-CII': one(cii, 'BR-CL-01'),
        'ISO4217': same('ISO4217', one(ubl, 'BR-CL-04'), one(cii, 'BR-CL-04')),
        'UNTDID2005': one(ubl, 'BR-CL-06'),
        'UNTDID1153': same('UNTDID1153', one(ubl, 'BR-CL-07'), one(cii, 'BR-CL-07')),
        'UNTDID4451': one(ubl, 'BR-CL-08'),
        'ISO6523': same('ISO6523', one(ubl, 'BR-CL-11'), one(cii, 'BR-CL-11')),
        'UNTDID7143': same('UNTDID7143', one(ubl, 'BR-CL-13'), one(cii, 'BR-CL-13')),
        'ISO3166': same('ISO3166', one(ubl, 'BR-CL-14'), one(cii, 'BR-CL-14')),
        'UNTDID4461': same('UNTDID4461', one(ubl, 'BR-CL-16'), one(cii, 'BR-CL-16')),
        'UNTDID5305': same('UNTDID5305', one(ubl, 'BR-CL-17'), one(cii, 'BR-CL-17')),
        'UNTDID5189': same('UNTDID5189', one(ubl, 'BR-CL-19'), one(cii, 'BR-CL-19')),
        'UNTDID7161': same('UNTDID7161', one(ubl, 'BR-CL-20'), one(cii, 'BR-CL-20')),
        'VATEX': same('VATEX', one(ubl, 'BR-CL-22'), one(cii, 'BR-CL-22')),
        'UNECE-REC20': same('UNECE-REC20', one(ubl, 'BR-CL-23'), one(cii, 'BR-CL-23')),
        'MIME': same('MIME', one(ubl, 'BR-CL-24'), one(cii, 'BR-CL-24')),
        'EAS': same('EAS', one(ubl, 'BR-CL-25'), one(cii, 'BR-CL-25')),
        'VAT-PREFIX': one(ubl, 'BR-CO-09'),
    }
    with open(CODELISTS, 'w', encoding='utf-8', newline='\n') as f:
        f.write('# Code lists for the plausibility check. Generated by tools/gen-data.py from the\n')
        f.write('# EN 16931 validation artefacts of CEN (github.com/ConnectingEurope/eInvoicing-EN16931,\n')
        f.write('# EUPL 1.2). Only the code values are taken. Format: [NAME] followed by codes.\n')
        for name in sorted(lists):
            codes = sorted(set(lists[name]), key=lambda c: c.encode())
            f.write('\n[%s]\n' % name)
            for i in range(0, len(codes), 16):
                f.write(' '.join(codes[i:i + 16]) + '\n')
    print('written', CODELISTS, '(%d lists)' % len(lists))


def read_codelists():
    lists, cur = {}, None
    for line in read(CODELISTS).splitlines():
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        m = re.match(r'\[(.+)\]$', line)
        if m:
            cur = m.group(1)
            lists[cur] = []
        else:
            lists[cur].extend(line.split())
    return lists


def read_rules():
    rules = []
    for n, line in enumerate(read(RULES).splitlines(), 1):
        if not line.strip() or line.startswith('#'):
            continue
        parts = line.split('\t')
        if len(parts) != 3 or parts[1] not in ('error', 'warning', 'info'):
            sys.exit('%s:%d: expected ID<TAB>error|warning|info<TAB>text' % (RULES, n))
        rules.append(parts)
    ids = [r[0] for r in rules]
    dup = sorted({i for i in ids if ids.count(i) > 1})
    if dup:
        sys.exit('duplicate rule ids: %s' % dup)
    return rules


def pas(s):
    return "'" + s.replace("'", "''") + "'"


def write_inc(rules, lists):
    rules = sorted(rules, key=lambda r: r[0].encode())
    sev = {'error': 'abError', 'warning': 'abWarning', 'info': 'abInfo'}
    o = ['{ Generated by tools/gen-data.py from data/rules.txt and data/codelists.txt.',
         '  Do not edit. }', '', 'const']
    o.append('  RuleTable: array[0..%d] of TRuleInfo = (' % (len(rules) - 1))
    for k, (i, s, t) in enumerate(rules):
        o.append('    (ID: %s; Severity: %s; Text: %s)%s' % (
            pas(i), sev[s], pas(t), ',' if k < len(rules) - 1 else ''))
    o.append('  );')
    for name in sorted(lists):
        codes = sorted(set(lists[name]), key=lambda c: c.encode())
        ident = 'CL_' + re.sub(r'[^A-Za-z0-9]', '_', name).upper()
        o.append('')
        o.append('  %s: array[0..%d] of string = (' % (ident, len(codes) - 1))
        for k in range(0, len(codes), 12):
            chunk = ', '.join(pas(c) for c in codes[k:k + 12])
            o.append('    ' + chunk + (',' if k + 12 < len(codes) else ''))
        o.append('  );')
    with open(INC, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(o) + '\n')
    print('written', INC, '(%d rules, %d code lists)' % (len(rules), len(lists)))


def check_usage(rules):
    if not os.path.exists(CHECK):
        return
    # literal IDs; category rules are built from a prefix (e.g. 'BR-S' + '-01')
    used = {u for u in re.findall(r"'((?:BR|PEPPOL)-[A-Za-z0-9-]+)'", read(CHECK)) if re.search(r'\d', u)}
    for prefix in re.findall(r"'(BR-[A-Z]+)'", read(CHECK)):
        used |= {r[0] for r in rules if re.match(re.escape(prefix) + r'-\d+$', r[0])}
    defined = {r[0] for r in rules}
    missing = sorted(used - defined)
    if missing:
        sys.exit('rule ids used in abdecker.check.pas but not in data/rules.txt: %s' % missing)
    unused = sorted(defined - used)
    if unused:
        print('note: rules defined but not used:', ' '.join(unused))


def write_openapi_inc():
    import json
    text = read(OPENAPI)
    json.loads(text)  # must be valid JSON
    if any(ord(c) > 126 for c in text):
        sys.exit('%s: ASCII only, please (use \\uXXXX)' % OPENAPI)
    o = ['{ Generated by tools/gen-data.py from data/openapi.json. Do not edit. }', '',
         'const', '  OpenApiJson =']
    lines = text.rstrip('\n').split('\n')
    for k, line in enumerate(lines):
        # Delphi: a string literal has at most 255 characters
        parts = [line[i:i + 200] for i in range(0, len(line), 200)] or ['']
        expr = ' + '.join(pas(p) for p in parts)
        o.append('    ' + expr + (' + #10 +' if k < len(lines) - 1 else ';'))
    with open(OPENAPI_INC, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(o) + '\n')
    print('written', OPENAPI_INC, '(%d lines)' % len(lines))


if __name__ == '__main__':
    if os.path.isdir(RULES_DIR):
        extract_codelists()
    all_rules = read_rules()
    check_usage(all_rules)
    write_inc(all_rules, read_codelists())
    write_openapi_inc()
